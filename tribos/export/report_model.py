def build_report_model(
    question: str,
    message: ExportMessage | dict[str, Any],
    *,
    stored_manifest: dict[str, Any] | None = None,
) -> ReportModel:
    msg = message if isinstance(message, ExportMessage) else ExportMessage.model_validate(message)
    provenance: Literal["server_store", "client_supplied"] = "server_store" if stored_manifest else "client_supplied"
    manifest = stored_manifest or (msg.run_manifest if isinstance(msg.run_manifest, dict) else {}) or {}
    if manifest:
        from tribos.provenance.run_manifest import client_view

        # The stored copy holds server paths (inputs and error texts); a report shows only basenames.
        manifest = client_view(manifest)
    artifacts = msg.execution_artifacts if isinstance(msg.execution_artifacts, dict) else {}
    answer = strip_verification_banner(msg.content).strip()

    notices: list[str] = []
    matches: bool | None = None
    expected = _text(manifest.get("response_sha256"))
    if expected:
        matches = content_sha256(msg.content) == expected
        if not matches:
            notices.append(CONTENT_DIFFERS_NOTICE)
    if provenance == "client_supplied":
        notices.append(
            "Provenance: client supplied. This answer could not be matched to a run stored on this server, "
            "so its run details are shown as submitted."
        )

    verification = _verification(msg.verification_report)
    viv = artifacts.get("vivarix")
    citations = _citations(artifacts, msg.citations, answer)
    tables = _data_tables(artifacts)
    shown_question = _question(question)
    task_source = msg.task_status or manifest.get("task_status")
    check = None
    if provenance == "server_store":
        notices += _stored_run_mismatches(manifest, verification, viv)
        # PRV-001: compare every section the stored manifest can confirm; the stored question and task win.
        from .provenance_check import check_report, mark_rows

        check = check_report(
            manifest, artifacts=artifacts, citation_rows=[c.model_dump() for c in citations],
            posted_task=msg.task_status, posted_question=shown_question, verification=verification,
        )
        notices += check.notices
        mark_rows(tables, check.bad_row_keys)
        for c in citations:
            c.in_stored_run = source_key(c.model_dump()) not in check.unmatched_citation_keys
        if _text(manifest.get("query")):
            shown_question = _question(manifest.get("query"))
        if isinstance(manifest.get("task_status"), dict) and manifest.get("task_status"):
            task_source = manifest.get("task_status")
    footer = _footer(provenance, manifest, notices, check)
    metadata = _run_metadata(manifest, msg, provenance)
    if check is not None and check.unchecked:
        metadata.append(["Not checked against the stored run", ", ".join(check.unchecked)])
    report = ReportModel(
        generated_at=datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
        question=shown_question,
        answer_markdown=answer,
        provenance=provenance,
        content_matches_run=matches,
        notices=notices,
        run_id=_text(manifest.get("run_id")) or None,
        model=_model_label(manifest, msg),
        task=_task(task_source),
        plot_png=decode_plot(viv.get("plot_base64_png")) if isinstance(viv, dict) else None,
        simulation=_simulation(viv),
        data_tables=tables,
        citations=citations,
        verification=verification,
        limitations=_limitations(manifest, artifacts, verification),
        run_metadata=metadata,
        checked_against_run=list(check.checked) if check is not None else [],
        not_checked=list(check.unchecked) if check is not None else [],
        footer=footer,
        tool_calls=[
            ToolCallRow(
                seq=int(c.get("seq") or i),
                tool=_text(c.get("tool_name")),
                inputs=_short_inputs(c.get("inputs") or c.get("raw_inputs") or {}),
                status="success" if c.get("success") else _text(c.get("error_type")) or "error",
                output_sha256=_text(c.get("output_sha256"))[:12],
            )
            for i, c in enumerate(manifest.get("tool_calls") or [], start=1)
            if isinstance(c, dict)
        ],
        reproducibility=_reproducibility(manifest),
    )
    return ReportModel.model_validate({
        **_clean_strings(report.model_dump()),
        "plot_png": report.plot_png,
        "manifest": manifest or None,
    })


def _footer(provenance: str, manifest: dict[str, Any], notices: list[str], check: Any) -> str:
    """The closing statement, true for this report's provenance (PRV-001)."""
    if provenance != "server_store":
        return FOOTER_CLIENT
    if not [c for c in manifest.get("tool_calls") or [] if isinstance(c, dict)]:
        return FOOTER_NO_TOOLS
    if notices or (check is not None and check.mismatch):
        return FOOTER_MISMATCH
    if check is not None and check.unchecked:
        return FOOTER_PARTIAL
    return FOOTER_TEXT


def _stored_run_mismatches(
    manifest: dict[str, Any], verification: VerificationSection | None, viv: Any
) -> list[str]:
    """The posted verification and simulation values are client data; check them against the stored run."""
    out: list[str] = []
    final = (manifest.get("verification") or {}).get("final") or {}
    if verification is not None and final:
        score_differs = (
            _num(final.get("score")) is not None
            and verification.score is not None
            and abs(float(final["score"]) - verification.score) > 1e-6
        )
        passed_differs = isinstance(final.get("passed"), bool) and verification.passed is not None and final["passed"] != verification.passed
        if score_differs or passed_differs:
            stored_score = _num(final.get("score"))
            out.append(
                "The verification report differs from the stored run, which recorded "
                + ("passed" if final.get("passed") else "not passed")
                + (f" with score {stored_score:.2f}" if stored_score is not None else "")
                + "."
            )
    posted = viv.get("final_concentrations") if isinstance(viv, dict) else None
    recorded = next(
        (
            (c.get("output_digest") or {}).get("final_concentrations")
            for c in manifest.get("tool_calls") or []
            if isinstance(c, dict) and c.get("tool_name") in ("vivarix_simulate_time_course", "dynamis_simulate_ode") and c.get("success")
        ),
        None,
    )
    if isinstance(posted, dict) and isinstance(recorded, dict):
        same = set(posted) == set(recorded) and all(
            _num(posted[k]) is not None and _num(recorded[k]) is not None
            and abs(float(posted[k]) - float(recorded[k])) <= 1e-9 * max(1.0, abs(float(recorded[k])))
            for k in recorded
        )
        if not same:
            out.append("The simulation values differ from the Vivarix output recorded for this run.")
    return out


def _frequency(value: Any) -> str:
    """Allele frequencies at three significant figures: 1.369283412911521e-06 -> '1.37e-6'."""
    try:
        f = float(value)
    except (TypeError, ValueError):
        return _text(value)
    if f == 0:
        return "0"
    text = f"{f:.3g}"
    return re.sub(r"e([+-])0*(\d)", lambda m: "e" + ("-" if m.group(1) == "-" else "") + m.group(2), text)


def fmt_number(value: float | None) -> str:
    if value is None:
        return ""
    return f"{value:.6g}"


# The question becomes the report's title up to this length; longer ones get their own Question section.
TITLE_QUESTION_MAX = 220
# The facts shown under the title, in order (the full list is in the Run metadata section).
HEADLINE_FIELDS = ("Run started", "Duration", "Model", "Architecture", "Web search")


def report_headline(report: ReportModel) -> list[list[str]]:
    rows = dict(report.run_metadata)
    return [[k, rows[k]] for k in HEADLINE_FIELDS if rows.get(k)] + [["Generated", report.generated_at]]


def report_kind(report: ReportModel) -> str:
    """'Investigation report': the title without the brand name, for places that already show the Tribos mark."""
    kind = re.sub(r"^\s*Tribos\s+", "", report.title or "").strip()
    return kind[:1].upper() + kind[1:].lower() if kind else "Report"


def question_is_title(report: ReportModel) -> bool:
    return 0 < len((report.question or "").strip()) <= TITLE_QUESTION_MAX


def report_markdown(report: ReportModel, plot_path: str | None = None) -> str:
    """The whole report as Markdown. plot_path names the simulation image next to it (the bundle's simulation.png);
    without one, the .md says where the plot is instead of linking a file that is not there."""
    question = (report.question or "").strip()
    in_title = question_is_title(report)
    title = (question[:1].upper() + question[1:]) if in_title else report.title
    out: list[str] = [f"**Tribos** · {report_kind(report)}", "", f"# {_md_heading(title)}", ""]
    headline = report_headline(report)
    out += ["| " + " | ".join(_md_cell(k) for k, _ in headline) + " |", "|" + " --- |" * len(headline)]
    out += ["| " + " | ".join(_md_cell(v) for _, v in headline) + " |", ""]
    for notice in report.notices:
        out += [f"> **Notice:** {notice}", ""]
    if not in_title:
        out += ["## Question", "", question or "_No question was supplied._", ""]
    if report.task:
        out += ["## Task status", ""] + [f"- {line}" for line in task_lines(report.task)] + [""]
    out += ["## Answer", "", report.answer_markdown, ""]
    if report.simulation and (report.simulation.rows or report.plot_png):
        sim = report.simulation
        out += ["## Simulation", ""]
        title = " ".join(x for x in (sim.model_id, f"({sim.model_name})" if sim.model_name else "") if x)
        if title:
            out += [f"Model: {title}" + (f", duration {fmt_number(sim.duration)} {sim.time_unit}".rstrip() if sim.duration is not None else ""), ""]
        if report.plot_png:
            out += [f"![Simulation time course]({plot_path})" if plot_path
                    else "_The simulation time-course plot is included in the PDF and Word exports._", ""]
        if sim.rows:
            unit = f" ({sim.quantity_unit})" if sim.quantity_unit else ""
            has_ss = any(r.steady_state is not None for r in sim.rows)
            out += [f"| Species | Initial{unit} | Final{unit} |" + (f" Steady state{unit} |" if has_ss else ""),
                    "| --- | --- | --- |" + (" --- |" if has_ss else "")]
            for r in sim.rows:
                line = f"| {_md_cell(r.species)} | {fmt_number(r.initial)} | {fmt_number(r.final)} |"
                out.append(line + (f" {fmt_number(r.steady_state)} |" if has_ss else ""))
            out.append("")
    for table in report.data_tables:
        out += [f"## {table.title}", ""]
        out += ["| " + " | ".join(_md_cell(h) for h in table.header) + " |", "|" + " --- |" * len(table.header)]
        out += ["| " + " | ".join(_md_cell(c) for c in row) + " |" for row in table.rows]
        if table.note:
            out += ["", f"_{table.note}_"]
        out.append("")
    out += ["## Sources and citations", ""]
    if report.citations:
        for c in report.citations:
            out.append(f"{c.n}. {citation_line(c)}")
    else:
        out.append("No structured evidence records accompany this answer.")
    out += ["", "## Verification", ""]
    out += verification_lines(report.verification)
    out += ["", "## Evidence limitations", ""]
    out += [f"- {lim}" for lim in report.limitations] or ["No limitations were recorded."]
    out += ["", "## Run metadata", "", "| Field | Value |", "| --- | --- |"]
    out += [f"| {_md_cell(k)} | {_md_cell(v)} |" for k, v in report.run_metadata]
    out += ["", "## Reproducibility", ""]
    if report.tool_calls:
        out += ["| # | Tool | Inputs | Status | Output sha256 |", "| --- | --- | --- | --- | --- |"]
        out += [f"| {t.seq} | {_md_cell(t.tool)} | `{_md_cell(t.inputs)}` | {t.status} | {t.output_sha256} |" for t in report.tool_calls]
    else:
        out.append("No tool calls were recorded for this answer.")
    if report.reproducibility:
        out += [""] + [f"- **{k}**: {v}" for k, v in report.reproducibility]
    out += ["", "---", "", f"_{report.footer}_", ""]
    return "\n".join(out)


def _md_heading(value: Any) -> str:
    return " ".join(_text(value).split()).lstrip("#").strip()


def _md_cell(value: Any) -> str:
    return _text(value).replace("|", "\\|").replace("\n", " ")


MAX_CITATION_AUTHORS = 3


def _short_authors(authors: str) -> str:
    """'A, B, C, D, ...' -> 'A, B, C et al.'; lists that already end in 'et al.' are kept."""
    text = authors.strip().rstrip(".")
    names = [n.strip() for n in text.split(",") if n.strip()]
    if len(names) > MAX_CITATION_AUTHORS and "et al" not in names[-1]:
        return ", ".join(names[:MAX_CITATION_AUTHORS]) + " et al."
    return text + "." if text.endswith("et al") else text


def _short_journal(journal: str) -> str:
    """NLM qualifiers off: 'European journal of cancer (Oxford, England : 1990)' -> 'European journal of cancer'."""
    return re.sub(r"\s*\([^()]*\)\s*$", "", journal or "").strip()


def citation_parts(c: ReportCitation) -> dict[str, Any]:
    """A citation's pieces, for renderers that style them (bold title, italic venue, muted link)."""
    ids = []
    if c.pmid:
        ids.append(f"PMID {c.pmid}")
    if c.doi:
        ids.append(f"DOI {c.doi}")
    id_type = (c.id_type or "").lower()
    # A "url" id repeats the link that follows; PMID and DOI ids are listed above already.
    if c.id and id_type and id_type not in ("pmid", "doi", "url") and c.id not in (c.url or ""):
        ids.append(f"{id_type.upper()} {c.id}")
    flags = []
    if c.in_stored_run is False:
        flags.append("not in stored run")
    if c.cited_in_answer:
        flags.append("cited in answer")
    if c.grade:
        flags.append(c.grade)
    if c.integrity:
        flags.append(c.integrity.replace("_", " "))
    if c.retracted:
        flags.append("RETRACTED")
    if c.authority in ("regulatory", "trial_registry", "manufacturer"):
        flags.append(SOURCE_AUTHORITY_LABELS[c.authority])
    return {
        "title": (c.title or "").strip().rstrip("."),
        "authors": _short_authors(c.authors) if c.authors else "",
        "venue": ", ".join(x for x in (_short_journal(c.journal), c.year) if x),
        "ids": " · ".join(ids),
        "url": c.url or "",
        "flags": flags,
    }


def citation_line(c: ReportCitation) -> str:
    p = citation_parts(c)
    # Joined with ". ", so a part's own closing full stop ("et al.") is dropped first.
    parts = [x.rstrip(".") if x is not p["url"] else x for x in (p["title"], p["authors"], p["venue"], p["ids"], p["url"]) if x]
    text = ". ".join(parts) or "Untitled source"
    return text + (f" [{'; '.join(p['flags'])}]" if p["flags"] else "")


def task_lines(t: TaskSection) -> list[str]:
    lines = [f"Status: {t.status.replace('_', ' ')}"]
    if t.requested_operation:
        lines.append(f"Requested: {t.requested_operation.replace('_', ' ')}")
    if t.executed_operation or t.requested_operation:
        lines.append(f"Executed: {(t.executed_operation or 'nothing').replace('_', ' ')}")
    if t.request_match is False:
        lines.append("The executed operation does not match the request.")
    if t.reason:
        lines.append(f"Reason: {t.reason}")
    if t.grounding_status:
        lines.append(f"Evidence grounding: {t.grounding_status.replace('_', ' ')}")
    return lines


def verification_lines(v: VerificationSection | None) -> list[str]:
    if v is None:
        return ["No verification report accompanies this answer."]
    status = "passed" if v.passed else "did not pass" if v.passed is False else "unknown"
    score = f"{v.score:.2f} / 1.00" if v.score is not None else "not recorded"
    lines = [f"- Status: {status}", f"- Verification score: {score}"]
    if v.numerical_checks_passed is not None or v.numerical_checks_failed is not None:
        lines.append(f"- Numerical checks: {v.numerical_checks_passed or 0} passed, {v.numerical_checks_failed or 0} failed")
    if v.verified_identifiers:
        lines.append(f"- Verified identifiers: {', '.join(v.verified_identifiers)}")
    if v.claims:
        counts: dict[str, int] = {}
        for c in v.claims:
            counts[c.status or "unknown"] = counts.get(c.status or "unknown", 0) + 1
        lines.append("- Claims: " + ", ".join(f"{n} {status.replace('_', ' ')}" for status, n in sorted(counts.items())))
        for c in v.claims:
            if c.status in ("contradicted", "unsupported"):
                lines.append(f"  - [{c.status}] {c.claim}" + (f" ({c.reason})" if c.reason else ""))
            elif c.cited_source_supported is False:
                lines.append(f"  - [cited source did not support it] {c.claim}" + (f" ({c.reason})" if c.reason else ""))
    if v.defects:
        lines.append("- Defects:")
        for d in v.defects:
            claim = f" (claim: {d.claim})" if d.claim else ""
            lines.append(f"  - [{d.severity}] {d.category}: {d.description}{claim}")
    else:
        lines.append("- Defects: none")
    return lines
